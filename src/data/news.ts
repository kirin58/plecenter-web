export function getNewsById(id: number) {
  return newsItems.find((item) => item.id === id);
}

export function getRelatedNews(item: NewsItem, limit = 3) {
  return newsItems
    .filter((news) => news.id !== item.id)
    .sort((a, b) => {
      const aMatch = a.category === item.category ? 1 : 0;
      const bMatch = b.category === item.category ? 1 : 0;
      return bMatch - aMatch || b.id - a.id;
    })
    .slice(0, limit);
}
